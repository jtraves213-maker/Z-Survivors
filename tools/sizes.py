"""Evens out how big sprites draw in game.

Every hd/ strip draws at (frame pixels / density) world units. Rips come at very different pixel sizes, so this
measures each sprite's visible height and writes the density that makes it TARGET units tall into the
ART_DENSITY table in ../js/data.js (between the SIZES markers). Re-run after rebuilding any art.
Run:  python tools/sizes.py
"""
import os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADULT, KID, GRUNT = 32, 25, 21
TARGETS = {}
for n in ["goku", "goku_ssj", "goku_ssj2", "goku_god", "goku_blue", "goku_ui", "gohan", "gohan_ssj", "gohan_ssj2", "gohan_ult", "gohan_beast",
          "vegeta", "vegeta_ssj", "vegeta_ssj2", "vegeta_blue", "vegeta_ue", "piccolo", "piccolo_orange", "yamcha", "tien", "nail", "a18",
          "trunks", "trunks_ssj", "bardock", "sgoku_base", "sgoku_ssj", "sgoku_god", "sgoku_blue", "sgoku_ui",
          "svegeta_base", "svegeta_ssj", "svegeta_ssj2", "svegeta_blue", "svegeta_evo",
          "gogeta", "gogeta_ssj", "gogeta_blue", "vegito", "vegito_ssj", "vegito_blue", "black", "rose"]:
    TARGETS[n] = ADULT
TARGETS.update({"goku_ssj3": 36, "sgoku_ui": 33})
for n in ["krillin", "goten", "goten_ssj", "gotenks", "gotenks_ssj", "gotenks_ssj3"]:
    TARGETS[n] = KID
for n in ["rr_yellow", "rr_bazooka", "rr_silver", "rr_murasaki", "rr_metallitron", "fz_soldier", "fz_cui", "fz_appule", "fz_orlen",
          "cell_jr", "namekian", "namekian_b", "buu_pink", "buu_grey", "buu_purple", "buu_green"]:
    TARGETS[n] = GRUNT
TARGETS.update({"saiba": 14, "saiba_dark": 14})


def visible_height(name):
    im = Image.open(os.path.join(ROOT, "art", "hd", name + ".png"))
    h = im.height
    hs = [im.crop((i * h, 0, (i + 1) * h, h)).getbbox() for i in range(im.width // h)]
    return max(b[3] - b[1] for b in hs if b)


def main():
    rows = []
    for n, t in TARGETS.items():
        d = round(visible_height(n) / t, 2)
        rows.append("'hd/%s': %s" % (n, d))
    body = "  // SIZES (generated by tools/sizes.py)\n  const ART_DENSITY = {\n" + "".join(
        "    " + ", ".join(rows[i:i + 6]) + ",\n" for i in range(0, len(rows), 6)) + "  };\n  // /SIZES\n"
    p = os.path.join(ROOT, "js", "data.js")
    s = open(p, encoding="utf-8").read()
    if "// SIZES" in s:
        s = re.sub(r"  // SIZES \(generated.*?// /SIZES\n", lambda m: body, s, flags=re.S)
    else:
        s = re.sub(r"  const ART_DENSITY = \{.*?\};\n", lambda m: body, s, flags=re.S, count=1)
    open(p, "w", encoding="utf-8", newline="\n").write(s)
    print("sized", len(rows), "sprites")


if __name__ == "__main__":
    main()
